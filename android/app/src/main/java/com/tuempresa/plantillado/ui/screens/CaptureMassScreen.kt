@Composable
fun CaptureMassScreen(
    onBack: () -> Unit,
    onStartProcessing: () -> Unit,
) {
    Scaffold { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp, Alignment.CenterVertically),
            horizontalAlignment = Alignment.CenterHorizontally,
        ) {
            Text("Captura masiva (cámara/galería) (stub)")
            Button(onClick = onStartProcessing) { Text("Procesar") }
            OutlinedButton(onClick = onBack) { Text("Volver") }
        }
